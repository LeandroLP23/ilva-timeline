"""port.js: quay of the 5th pier, the plant's conveyor belts in the port, jetties and breakwaters (OSM).

The conveyors take their height from the MASE 2008-2010 laser survey (peak within 6 m of the centre of each stretch),
where available; otherwise 10 m.
"""
import json, math, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_heights as BH  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
M = 111320


def conveyor(coords, width=4.0):
    """Line -> polygons per stretch, `width` metres wide."""
    out = []
    for (x1, y1), (x2, y2) in zip(coords, coords[1:]):
        k = math.cos(math.radians(y1))
        dx, dy = (x2 - x1) * M * k, (y2 - y1) * M
        L = math.hypot(dx, dy) or 1
        ox, oy = -dy / L * width / 2 / (M * k), dx / L * width / 2 / M
        ring = [[x1 + ox, y1 + oy], [x2 + ox, y2 + oy], [x2 - ox, y2 - oy], [x1 - ox, y1 - oy]]
        ring = [[round(a, 6), round(b, 6)] for a, b in ring]
        out.append(ring + [ring[0]])
    return out


# piers granted to the steelworks (ILVA note DIR/407 of 11/11/2013), cut from the OSM coastline:
# each pier is the stretch of coast south of the root, closed between the two corners where it leaves the quay.
# Pier order: port master plan (PRP) of the Port Authority, sheet C2.12.
ROOT = 40.4787
PIERS = [  # name, longitudes bracketing the tip, year
    ('4° sporgente', (17.203, 17.207), 1974),
    ('3° sporgente', (17.209, 17.213), 1973),
    ('2° sporgente', (17.2145, 17.217), 1965),
]


def piers():
    el = json.load(open(os.path.join(HERE, 'sources', 'osm-piers', 'port2.json'), encoding='utf-8'))['elements']
    g = [(q['lon'], q['lat']) for q in next(e for e in el if e['id'] == 176922694)['geometry']]
    out = []
    for name, window, since in PIERS:
        tip = [k for k, p in enumerate(g) if p[1] < ROOT and window[0] < p[0] < window[1]]
        i, j = min(tip), max(tip)
        while g[i - 1][1] < ROOT:
            i -= 1
        while g[j + 1][1] < ROOT:
            j += 1
        ring = [[round(x, 6), round(y, 6)] for x, y in g[i - 1:j + 2]]  # including the two corners at the root
        out.append({'type': 'Feature', 'properties': {'kind': 'concession', 'name': name, 'since': since},
                    'geometry': {'type': 'Polygon', 'coordinates': [ring + [ring[0]]]}})
    return out


def main():
    BH.load()
    el = json.load(open(os.path.join(HERE, 'osm-port.json'), encoding='utf-8'))['elements']
    feats, lines, concessions = [], [], piers()
    for e in el:
        t = e.get('tags', {})
        g = [(p['lon'], p['lat']) for p in e.get('geometry', [])]
        if not g:
            continue
        if 'Sporgente' in t.get('name', '') and 'Acciaierie' in t.get('name', ''):
            feats.append({'type': 'Feature', 'properties': {'kind': 'quay', 'h': 2, 'name': '5° sporgente'},
                          'geometry': {'type': 'Polygon', 'coordinates': [[list(p) for p in g]]}})
            concessions.append({'type': 'Feature', 'properties': {'kind': 'concession', 'name': '5° sporgente', 'since': 1965},
                                'geometry': {'type': 'Polygon', 'coordinates': [[list(p) for p in g]]}})
        elif t.get('man_made') == 'goods_conveyor' and ('Mittal' in t.get('operator', '') or 'ILVA' in t.get('operator', '')):
            for ring in conveyor(g):
                cx = sum(p[0] for p in ring[:4]) / 4
                cy = sum(p[1] for p in ring[:4]) / 4
                peak = BH.nearby_peak(cx, cy, 6)
                h = peak[0] if peak and peak[0] >= 4 else 10
                feats.append({'type': 'Feature', 'properties': {'kind': 'conveyor', 'h': round(h, 1), 'base': round(max(0, h - 3), 1),
                                                                'port': True, 'group': f"conveyor-port-{e['id']}"},
                              'geometry': {'type': 'Polygon', 'coordinates': [ring]}})
        elif t.get('man_made') in ('pier', 'breakwater'):
            lines.append({'type': 'Feature', 'properties': {'kind': t['man_made']},
                          'geometry': {'type': 'LineString', 'coordinates': [list(p) for p in g]}})
    with open(os.path.join(HERE, 'port.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Generated by build_port.py: the plant\'s port from OpenStreetMap; conveyor heights from the MASE LiDAR.\n')
        fh.write('window.PORT=' + json.dumps({'volumes': {'type': 'FeatureCollection', 'features': feats},
                                             'lines': {'type': 'FeatureCollection', 'features': lines},
                                             'concessions': {'type': 'FeatureCollection', 'features': concessions}}, separators=(',', ':')) + ';\n')
    print(len(feats), 'volumes,', len(lines), 'jetty and breakwater lines,', len(concessions), 'concession areas')


if __name__ == '__main__':
    main()
