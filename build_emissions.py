"""emissions.js: air emissions declared by the plant to the European register (E-PRTR / Industrial Emissions Portal, EEA).

Source: Tableau view of the EEA portal, exported as CSV, for site IT.CAED/741231003.SITE.
Only the rows of facility 2007001763 (the steelworks) are kept: since 2015 some series
(e.g. CO2) also include the power plant and would not be comparable.
"""
import csv, io, json, os, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
URL = 'https://tableau-public.discomap.eea.europa.eu/views/Browsethedata_6_platform/Pollutant_releases.csv'
SITE = 'IT.CAED/741231003.SITE'
POLLUTANTS = {
    'pm10': ('Particulate matter (PM10)', 1e-3, 't'),               # kg -> tonnes
    'dioxins': ('PCDD + PCDF (dioxins + furans) (as Teq)', 1e3, 'g TEQ'),  # kg -> grams
    'benzene': ('Benzene', 1e-3, 't'),
    'pah': ('Polycyclic aromatic hydrocarbons (PAHs)', 1e-3, 't'),
}


def download(name):
    q = urllib.parse.urlencode({'SiteId': SITE, 'pollutant': name}, quote_via=urllib.parse.quote)
    req = urllib.request.Request(f'{URL}?{q}', headers={'User-Agent': 'Mozilla/5.0'})
    return list(csv.DictReader(io.StringIO(urllib.request.urlopen(req, timeout=120).read().decode('utf-8'))))


def number(row):
    # small values in scientific notation in the 'amount<1' column, the others with spaces as separators
    v = (row.get('amount<1') or '').strip() or row['amount'].replace(' ', '').replace(' ', '')
    return float(v)


def main():
    series = {}
    for key, (name, factor, unit) in POLLUTANTS.items():
        rows = [r for r in download(name) if '(2007001763)' in r['facility']]
        series[key] = {'name': name, 'unit': unit,
                       'values': {int(r['Year']): round(number(r) * factor, 3) for r in rows}}
        print(key, unit, series[key]['values'])
    with open(os.path.join(HERE, 'emissions.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Generated by build_emissions.py: air emissions declared to the European E-PRTR register (EEA), Taranto plant.\n')
        fh.write('window.EMISSIONS = ' + json.dumps(series, ensure_ascii=False) + ';\n')


if __name__ == '__main__':
    main()
